import type { SVGProps } from "react";

/*
 * The map screens' icons: simple line icons in currentColor, decorative
 * (aria-hidden), so the button around each one must have a label. None of
 * them points a way, so none flips in right-to-left.
 */

type IconProps = SVGProps<SVGSVGElement> & { size?: number };

function Icon({ size = 20, children, ...props }: IconProps) {
  return (
    <svg
      viewBox="0 0 24 24"
      width={size}
      height={size}
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      focusable="false"
      {...props}
    >
      {children}
    </svg>
  );
}

